import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {loadRegistry} from './command-registry.mjs';
import {batchPreflight,coveredActions} from './batch-preflight.mjs';
const r=await loadRegistry(path.dirname(fileURLToPath(import.meta.url)));
assert.deepEqual(coveredActions(),[...r.all.get('batch').tool.inputSchema.properties.steps.items.properties.action.enum].sort());
const p=(x,y)=>({x,y}),wall={action:'wall',levelId:'$l',typeId:2,heightMm:3000,start:p(0,0),end:p(3000,0),alias:'w'};
const level={action:'level',name:'N1',elevationMm:0,alias:'l'};
const a=steps=>batchPreflight({expectedPath:'C:/Sandbox/Test.rvt',steps},r);
assert.equal(a([level,wall]).ok,true);
assert.equal(a([wall,level]).ok,false);
assert.equal(a([level,{...wall,end:p(0,0)}]).ok,false);
assert.equal(a([level,wall,{...wall}]).ok,false);
assert.equal(a([level,{...wall,heightMm:-1}]).ok,false);
assert.equal(a([level,{...wall,unexpected:1}]).ok,false);
assert.equal(a([level,{action:'floor',levelId:'$l',typeId:4,points:[p(0,0),p(3000,0),p(0,3000)]}]).ok,true);
assert.equal(a([level,{action:'floor',levelId:'$l',typeId:4,points:[p(0,0),p(3000,0),p(0,0)]}]).ok,false);
assert.equal(a([level,{action:'duct_sized',levelId:'$l',typeId:3,systemTypeId:5,start:{x:0,y:0,z:0},end:{x:3000,y:0,z:0},widthMm:200}]).ok,false);
console.log('BATCH_PREFLIGHT_TESTS=PASS; actions='+coveredActions().length);
